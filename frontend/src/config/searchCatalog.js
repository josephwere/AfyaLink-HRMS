export function getSearchCatalog(user) {
  const role = normalizeRole(user?.role || "");
  const roleItems = ROLE_ITEMS[role] || [];
  const merged = [...roleItems, ...BASE_ITEMS];

  const seen = new Set();
  return merged.filter((item) => {
    if (seen.has(item.path)) return false;
    seen.add(item.path);
    return true;
  });
}
